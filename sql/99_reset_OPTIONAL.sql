-- OPTIONAL AND DESTRUCTIVE. Never run as part of ordinary setup.
-- Oracle DDL commits immediately; this cannot be rolled back.
-- To opt in, change the constant below to 'DROP HW BANKING TABLES'.
DECLARE
  confirmation VARCHAR2(30) := 'NO';
BEGIN
  IF confirmation <> 'DROP HW BANKING TABLES' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Reset refused: explicit confirmation required.');
  END IF;
  EXECUTE IMMEDIATE 'DROP TABLE HW_LOAN_PAYMENTS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_LOANS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_LOAN_TYPES';
  EXECUTE IMMEDIATE 'DROP TABLE HW_TRANSACTIONS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_ACCOUNT_HOLDERS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_ACCOUNTS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_ACCOUNT_TYPES';
  EXECUTE IMMEDIATE 'DROP TABLE HW_EMPLOYEES';
  EXECUTE IMMEDIATE 'DROP TABLE HW_CUSTOMERS';
  EXECUTE IMMEDIATE 'DROP TABLE HW_BRANCHES';
END;
/
