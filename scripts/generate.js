import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { scenario } from '../scenario/banking.js';
import { checkScenario } from '../lib/validation.js';

const quote = value => `'${String(value).replaceAll("'", "''")}'`;
const table = entity => scenario.prefix + entity.name.toUpperCase();
const sqlType = field => ({
  integer: 'NUMBER(10)', money: 'NUMBER(12,2)', date: 'DATE',
  text: `VARCHAR2(${field.max} CHAR)`
})[field.type];
const literal = (value, field) => value == null ? 'NULL' :
  field.type === 'date' ? `TO_DATE(${quote(value)}, 'YYYY-MM-DD')` :
    typeof value === 'number' ? String(value) : quote(value);

export function artifacts() {
  checkScenario(scenario);
  let schema = '-- Generated by npm run generate. No existing tables are dropped.\n';
  let seed = '-- Generated synthetic data. Run once after 01_schema.sql.\nBEGIN\n';
  let erd = '# Banking ERD\n\nGenerated from `scenario/banking.js`; do not edit this file by hand.\n\n```mermaid\nerDiagram\n';
  let verify = '-- Expected counts apply immediately after seeding, before CRUD changes.\n';
  const counts = [];
  const orphans = [];
  for (const entity of scenario.entities) {
    const columns = [];
    erd += `  ${table(entity)} {\n`;
    for (const [key, field] of Object.entries(entity.fields)) {
      let column = `  ${key} ${sqlType(field)}`;
      if (key === 'id') column += ' PRIMARY KEY';
      else if (field.required) column += ' NOT NULL';
      if (field.unique) column += ' UNIQUE';
      if (field.ref) column += ` REFERENCES ${scenario.prefix}${field.ref.toUpperCase()}(id)`;
      const checks = [];
      if (field.min !== undefined) checks.push(`${key} ${field.exclusiveMin ? '>' : '>='} ${field.min}`);
      if (field.max !== undefined && field.type !== 'text') checks.push(`${key} <= ${field.max}`);
      if (field.type === 'text') checks.push(`TRIM(${key}) IS NOT NULL`, `LENGTH(TRIM(${key})) = LENGTH(${key})`);
      if (field.type === 'date') checks.push(`${key} = TRUNC(${key})`);
      if (field.enum) checks.push(`${key} IN (${field.enum.map(quote).join(', ')})`);
      if (checks.length) column += ` CHECK (${checks.join(' AND ')})`;
      columns.push(column);
      erd += `    ${field.type === 'text' ? 'VARCHAR2' : field.type === 'date' ? 'DATE' : 'NUMBER'} ${key}${key === 'id' ? ' PK' : field.ref ? ' FK' : field.unique ? ' UK' : ''}\n`;
      if (field.ref) {
        orphans.push(`SELECT '${entity.name}.${key}' AS relationship, COUNT(*) AS orphan_count FROM ${table(entity)} c WHERE c.${key} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM ${scenario.prefix}${field.ref.toUpperCase()} p WHERE p.id = c.${key})`);
      }
    }
    for (const keys of entity.unique) columns.push(`  UNIQUE (${keys.join(', ')})`);
    schema += `\nCREATE TABLE ${table(entity)} (\n${columns.join(',\n')}\n);\n`;
    erd += '  }\n';
    const keys = Object.keys(entity.fields);
    for (const row of entity.rows) {
      seed += `  INSERT INTO ${table(entity)} (${keys.join(', ')}) VALUES (${keys.map(key => literal(row[key], entity.fields[key])).join(', ')});\n`;
    }
    counts.push(`SELECT '${table(entity)}' AS table_name, COUNT(*) AS actual_rows, ${entity.rows.length} AS expected_rows FROM ${table(entity)}`);
  }
  for (const entity of scenario.entities) {
    for (const [key, field] of Object.entries(entity.fields)) {
      if (field.ref) erd += `  ${scenario.prefix}${field.ref.toUpperCase()} ${field.required ? '||' : '|o'}--o{ ${table(entity)} : "${key}"\n`;
    }
  }
  erd += '```\n\n`||` = exactly one parent; `|o` = zero or one parent; `o{` = zero or many children.\n\nEvery table has numeric `id` as its primary key. Foreign keys are labelled FK. A customer can hold many accounts and an account can have many customers through `HW_ACCOUNT_HOLDERS`; its `(account_id, customer_id)` pair is unique. Transactions may have no employee (self-service). Every other reference requires exactly one parent. Deletion is restricted: remove or reassign children first.\n\nBranches connect employees, accounts and loans. Account types classify accounts; loan types classify loans. Each loan belongs to a customer and an advisor. Payments reference both the repaid loan and the paying account. An account may have no transactions and a loan may have no payments yet. All amounts are synthetic RON values.\n';
  seed += '  COMMIT;\nEXCEPTION\n  WHEN OTHERS THEN\n    ROLLBACK;\n    RAISE;\nEND;\n/\n';
  verify += counts.join('\nUNION ALL\n') + ';\n\n-- All orphan_count values must be zero.\n' + orphans.join('\nUNION ALL\n') + ';\n';
  verify += `\n-- APEX-friendly alternative to DESCRIBE; restrict to this scenario's tables.\nSELECT table_name, column_name, data_type, nullable\nFROM user_tab_columns\nWHERE table_name IN (${scenario.entities.map(e => quote(table(e))).join(', ')})\nORDER BY table_name, column_id;\n\nSELECT table_name, constraint_type, status\nFROM user_constraints\nWHERE table_name IN (${scenario.entities.map(e => quote(table(e))).join(', ')})\nORDER BY table_name, constraint_type;\n`;
  const reset = `-- OPTIONAL AND DESTRUCTIVE. Never run as part of ordinary setup.\n-- Oracle DDL commits immediately; this cannot be rolled back.\n-- To opt in, change the constant below to 'DROP HW BANKING TABLES'.\nDECLARE\n  confirmation VARCHAR2(30) := 'NO';\nBEGIN\n  IF confirmation <> 'DROP HW BANKING TABLES' THEN\n    RAISE_APPLICATION_ERROR(-20001, 'Reset refused: explicit confirmation required.');\n  END IF;\n${[...scenario.entities].reverse().map(e => `  EXECUTE IMMEDIATE 'DROP TABLE ${table(e)}';`).join('\n')}\nEND;\n/\n`;
  return { 'sql/01_schema.sql': schema, 'sql/02_seed.sql': seed, 'sql/04_verify.sql': verify, 'sql/99_reset_OPTIONAL.sql': reset, 'docs/erd.md': erd };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(artifacts())) {
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated file: ${path}. Run npm run generate.`);
      console.log(`Consistent: ${path}`);
    } else {
      await mkdir(path.slice(0, path.lastIndexOf('/')), { recursive: true });
      await writeFile(path, content);
      console.log(`Generated: ${path}`);
    }
  }
}
